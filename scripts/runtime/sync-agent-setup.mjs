import { existsSync, lstatSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { basename, dirname, join, relative } from 'node:path'
import { finish, label, parseFrontmatter, root, symbolicLinks, walk } from '../checks/lib.mjs'

// Generate only from this reference's canonical catalog, never a parent checkout.
const check = process.argv.includes('--check')
if (process.argv.slice(2).some(argument => argument !== '--check')) {
  throw new Error('Usage: node scripts/runtime/sync-agent-setup.mjs [--check]')
}
const outputs = new Map()
const failures = symbolicLinks(root).map(path => `${label(path)}: symbolic links are not portable`)
finish('Runtime source safety', failures, 'Runtime sources contain no symbolic links.')
const agents = walk(join(root, '.github/agents'), path => path.endsWith('.agent.md'))
const skills = walk(join(root, '.github/skills'))
if (!agents.length || !skills.length) throw new Error('Canonical agent and skill catalogs must not be empty')

outputs.set('.codex/config.toml', '# Generated by pnpm sync:setup. Models and permissions inherit from the user.\n[agents]\nenabled = true\n')
for (const file of agents) {
  const { data, content } = parseFrontmatter(file)
  if (!data?.name || !data.description || !/^[a-z][a-z0-9-]*$/.test(data.name)) {
    throw new Error(`${label(file)}: invalid agent metadata`)
  }
  const name = data.name.replaceAll('-', '_')
  const bootstrap = `Read AGENTS.md and ${label(file)} completely before acting. Follow the persona's scope and boundaries. Read every SKILL.md linked in its Related Skills section before task actions. Repository instructions and the user's current request remain authoritative.`
  outputs.set(`.codex/agents/${name}.toml`, [
    '# Generated by pnpm sync:setup from the canonical persona.',
    `name = ${JSON.stringify(name)}`,
    `description = ${JSON.stringify(data.description)}`,
    `developer_instructions = ${JSON.stringify(bootstrap)}`,
    ''
  ].join('\n'))
  // Preload the explicitly delegated skills; sibling links resolve in the Claude tree.
  const relatedSkills = [...content.matchAll(/\]\(\.\.\/skills\/([^/]+)\/SKILL\.md\)/g)].map(match => match[1])
  if (!relatedSkills.length) throw new Error(`${label(file)}: missing Related Skills links`)
  const claudeContent = content.replace(/\n---\n/, `\nskills:\n${relatedSkills.map(skill => `  - ${skill}`).join('\n')}\n---\n`)
  outputs.set(`.claude/agents/${data.name}.md`, claudeContent)
}
for (const file of skills) {
  const suffix = relative(join(root, '.github/skills'), file).split('\\').join('/')
  for (const consumer of ['.agents/skills', '.claude/skills']) {
    outputs.set(`${consumer}/${suffix}`, readFileSync(file))
  }
}

// Reject stale artifacts instead of deleting local work or quietly retaining old personas.
for (const directory of ['.codex/agents', '.claude/agents', '.agents/skills', '.claude/skills']) {
  for (const file of walk(join(root, directory))) {
    if (!outputs.has(label(file))) failures.push(`${label(file)}: stale runtime artifact; review and remove explicitly`)
  }
}
finish('Runtime inventory', failures, 'Runtime inventory contains no stale artifacts.')
for (const [path, content] of outputs) {
  const target = join(root, path)
  const expected = Buffer.from(content)
  if (check) {
    if (!existsSync(target) || !lstatSync(target).isFile()) failures.push(`${path}: missing runtime file`)
    else if (!readFileSync(target).equals(expected)) failures.push(`${path}: differs from canonical setup; run pnpm sync:setup`)
  } else {
    mkdirSync(dirname(target), { recursive: true })
    writeFileSync(target, expected)
  }
}
const skillCount = skills.filter(file => basename(file) === 'SKILL.md').length
finish('Runtime setup', failures, `Runtime setup ${check ? 'check passed' : 'generated'}: ${agents.length} Codex and Claude agents, ${skillCount} skills per runtime; ${outputs.size} files.`)
